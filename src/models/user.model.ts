import { Document, Schema, model } from "mongoose";
import { UserSchema } from "../schemas/user.schema";

export interface IUser extends Document, UserSchema {}

const userSchema = new Schema<IUser>(
  {
    username: {
      type: String,
      unique: true,
      required: true,
    },
    password: {
      type: String,
      required: true,
    },
    email: {
      type: String,
      required: true,
      unique: true,
    },
    name: {
      type: String,
      required: true,
    },
    profileImage: {
      type: String,
    },
    provider: {
      type: String,
      enum: ["google", "credentials"],
      required: true,
    },
    role: {
      type: String,
      enum: ["user", "admin"],
      default: "user",
    },
    isDeleted: {
      type: Boolean,
      default: false,
    },
  },
  {
    timestamps: {
      createdAt: true,
      updatedAt: true,
    },
  }
);

const UserModel = model<IUser>("User", userSchema);
export default UserModel;
